"""Generate src/common/figure_table.h, the figurine table built into libacioEx and the tag tools, from tmac.dll.

usage: python gen_figure_table.py <modules/tmac.dll>      (needs: pip install pefile)

Figure table: 463 x 144-byte entries at VA 0x1802B8F40. Per entry: qword 1 = English name, dwords 5..9 = tsum id,
chara, type, variant, skin id.

Series ("vol", the figurine waves): 20 lists of tsum ids at 0x18021B7F0 ({int n; int *ids} x 20; list i = Japanese
series i, list 0 a one-off), mapped per region by 0x1802D6180 ({?, J, A/Y, U} x 20 ints, -1 = not sold there):
Japanese series 3..5 don't exist in A/Y, the others are renumbered (J 6..19 = A/Y 3..16). A figurine works if any
series it is in exists in the cabinet's region. Bits in `series` / `series_en` are series numbers (J / A,Y numbering).
"""
import os
import struct
import sys

import pefile

TABLE, COUNT = 0x1802B8F40, 463
LISTS, REGIONS = 0x18021B7F0, 0x1802D6180


class Image:
    def __init__(self, path):
        pe = pefile.PE(path, fast_load=True)
        self.base = pe.OPTIONAL_HEADER.ImageBase
        self.img = pe.get_memory_mapped_image()

    def read(self, va, n):
        return self.img[va - self.base:va - self.base + n]

    def cstr(self, va):
        o = va - self.base
        return self.img[o:self.img.find(b"\0", o)].decode("cp932")


def c_string(s):
    out = ""
    for b in s.encode("utf-8"):
        out += chr(b) if 32 <= b < 127 and chr(b) not in '"\\?' else "\\%03o" % b
    return '"' + out + '"'


def main():
    tm = Image(sys.argv[1])
    in_lists = {}  # tsum id -> list indexes
    for i in range(20):
        n, _, p = struct.unpack("<iIQ", tm.read(LISTS + i * 16, 16))
        for tsum in struct.unpack("<%di" % n, tm.read(p, 4 * n)):
            in_lists.setdefault(tsum, []).append(i)
    region = [struct.unpack("<4i", tm.read(REGIONS + i * 16, 16)) for i in range(20)]

    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "common", "figure_table.h")
    released = 0
    with open(path, "w", newline="\n") as f:
        f.write("/* Generated by scripts/gen_figure_table.py from tmac.dll (463 x 144 bytes @ VA 0x1802B8F40). */\n")
        f.write("/* chara, type, variant, skin id, English name (UTF-8), series bits (Japan), series bits (English / A,Y) */\n")
        f.write("static const figure FIG[] = {\n")
        for i in range(COUNT):
            e = tm.read(TABLE + i * 144, 144)
            d, q = struct.unpack("<36I", e), struct.unpack("<18Q", e)
            name = tm.cstr(q[1]) if q[1] else ""
            jp = en = 0
            for li in in_lists.get(d[5], []):
                if region[li][1] >= 0:
                    jp |= 1 << region[li][1]
                if region[li][2] >= 0:
                    en |= 1 << region[li][2]
            released += bool(jp)
            f.write("    {%d, %d, %d, %du, %s, 0x%xu, 0x%xu},\n" % (d[6], d[7], d[8], d[9], c_string(name), jp, en))
        f.write("};\n#define NFIG ((int)(sizeof FIG / sizeof FIG[0]))\n#define NSERIES 20\n")
    print(COUNT, "figures,", released, "in a series ->", os.path.normpath(path))


if __name__ == "__main__":
    main()
